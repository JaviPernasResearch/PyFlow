class InterArrivalSourceSpec(BaseModel):
    """Generates items on a random inter-arrival schedule.

    Gap 2: Optional ``item_type`` and ``labels`` fields attach a fixed type and
    label set to every item generated by this source (model_item pattern).
    """
    type: Literal["InterArrivalSource"]
    id: str = Field(min_length=1, pattern=r"^[a-zA-Z][a-zA-Z0-9_]*$",
                    description="Unique identifier used to reference this element in connections")
    name: str = Field(description="Human-readable display name")
    interarrival: DistributionSpec = Field(description="Distribution of time between consecutive arrivals")
    # Gap 2 additions
    item_type: Optional[str] = Field(
        default=None,
        description=(
            "Optional item type tag stamped on every generated item. "
            "Appears in per-type sink stats. Example: \"Type1\""
        ),
    )
    labels: Optional[dict[str, str]] = Field(
        default=None,
        description=(
            "Optional label dict copied onto every generated item. "
            "Use string values; the label_expr service-time strategy converts them to float. "
            "Example: {\"PT1\": \"10\", \"PT2\": \"5\"}"
        ),
    )


class ItemsQueueSpec(BaseModel):
    type: Literal["ItemsQueue"]
    id: str = Field(min_length=1, pattern=r"^[a-zA-Z][a-zA-Z0-9_]*$")
    name: str
    capacity: int = Field(
        gt=0,
        description=(
            "Maximum number of items the queue can hold. "
            "When full, the queue rejects new items: the upstream source blocks "
            "and does NOT schedule its next arrival until space becomes available. "
            "Items are never silently dropped — the source retries when notified."
        ),
    )


class MultiServerSpec(BaseModel):
    type: Literal["MultiServer"]
    id: str = Field(min_length=1, pattern=r"^[a-zA-Z][a-zA-Z0-9_]*$")
    name: str
    num_servers: int = Field(gt=0, description="Number of parallel processing slots")
    service_time: ServiceTimeSpec = Field(
        description=(
            "Service time per item. Either a statistical distribution spec "
            "(expon / uniform / norm / triang) or a label_expr spec that reads "
            "the delay from an item label at runtime."
        )
    )


class SinkSpec(BaseModel):
    type: Literal["Sink"]
    id: str = Field(min_length=1, pattern=r"^[a-zA-Z][a-zA-Z0-9_]*$")
    name: str


