# Gap 3 — ScheduleSource: fixed job list released at specified times
# ---------------------------------------------------------------------------

class JobSpec(BaseModel):
    """One row in the ScheduleSource job table.

    Fields map directly to the ScheduleSource data_dict columns:
    Time, Name, Q (quantity), plus any number of label columns.

    Example:
        {"time": 0, "name": "J1", "qty": 1, "labels": {"PT1": "10", "PT2": "5"}}
    """
    time: float = Field(ge=0, description="Simulation time at which this job is released")
    name: str = Field(min_length=1, description="Job name; also used as the item type tag")
    qty: int = Field(default=1, gt=0, description="Number of identical items to release at this time")
    labels: dict[str, Any] = Field(
        default_factory=dict,
        description=(
            "Arbitrary key-value label pairs attached to each generated item. "
            "Values can be numbers or strings. "
            "Example: {\"PT1\": 10, \"PT2\": 5}"
        ),
    )


class ScheduleSourceSpec(BaseModel):
    """Releases a predefined list of jobs at specified simulation times.

    Use this instead of InterArrivalSource when you have a finite, known set of
    jobs (e.g. 8 jobs all released at t=0 with individual processing times).

    The jobs list is converted to the data_dict format expected by PyFlow's
    ScheduleSource. Columns beyond Time/Name/Q become item labels accessible
    via item.get_label_value() — and therefore usable with label_expr service times.

    Example (8 jobs at t=0 with PT1/PT2 labels):
        {
          "type": "ScheduleSource",
          "id": "src",
          "name": "Source",
          "jobs": [
            {"time": 0, "name": "J1", "qty": 1, "labels": {"PT1": 10, "PT2": 5}},
            {"time": 0, "name": "J2", "qty": 1, "labels": {"PT1": 5,  "PT2": 15}},
            ...
          ]
        }
    """
    type: Literal["ScheduleSource"]
    id: str = Field(min_length=1, pattern=r"^[a-zA-Z][a-zA-Z0-9_]*$")
    name: str
    jobs: list[JobSpec] = Field(min_length=1, description="Ordered list of job release records")

    def to_data_dict(self) -> dict:
        """Convert to the data_dict format accepted by PyFlow's ScheduleSource."""
        # Collect the superset of label keys across all jobs (preserve insertion order).
        label_keys: list[str] = []
        for job in self.jobs:
            for k in job.labels:
                if k not in label_keys:
                    label_keys.append(k)

        data: dict[str, list] = {"Time": [], "Name": [], "Q": []}
        for k in label_keys:
            data[k] = []

        for job in self.jobs:
            data["Time"].append(job.time)
            data["Name"].append(job.name)
            data["Q"].append(job.qty)
            for k in label_keys:
                data[k].append(job.labels.get(k, None))

        return data


ElementSpec = Annotated[
    Union[InterArrivalSourceSpec, ItemsQueueSpec, MultiServerSpec, SinkSpec, ScheduleSourceSpec],
    Field(discriminator="type"),
]


