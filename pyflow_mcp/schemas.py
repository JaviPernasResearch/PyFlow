"""Pydantic v2 models for every spec type accepted by the MCP tools."""

from typing import Annotated, Any, Literal, Optional, Union

from pydantic import BaseModel, Field, field_validator


# ---------------------------------------------------------------------------
# Distributions
# ---------------------------------------------------------------------------

class ExponDist(BaseModel):
    type: Literal["expon"]
    scale: float = Field(gt=0, description="Mean of the exponential distribution")


class UniformDist(BaseModel):
    type: Literal["uniform"]
    loc: float = Field(description="Lower bound")
    scale: float = Field(ge=0, description="Width (use 0 for a deterministic value equal to loc)")


class NormDist(BaseModel):
    type: Literal["norm"]
    loc: float = Field(description="Mean")
    scale: float = Field(gt=0, description="Standard deviation")


class TriangDist(BaseModel):
    type: Literal["triang"]
    c: float = Field(
        ge=0, le=1,
        description=(
            "Mode expressed as a fraction of the interval [loc, loc+scale]. "
            "c = (mode - loc) / scale. "
            "Example: triangle with min=2, mode=5, max=8 → loc=2, scale=6, c=0.5 (since (5-2)/6=0.5)."
        ),
    )
    loc: float = Field(description="Lower bound (minimum value)")
    scale: float = Field(gt=0, description="Width = max - min")


DistributionSpec = Annotated[
    Union[ExponDist, UniformDist, NormDist, TriangDist],
    Field(discriminator="type"),
]


# ---------------------------------------------------------------------------
# Gap 1 — Label-expression service time for MultiServer
# ---------------------------------------------------------------------------

class LabelExprSpec(BaseModel):
    """Service-time spec that reads the delay from an item label at runtime.

    The expression is evaluated as a Python expression with ``item`` in scope,
    so you can use ``item.get_label_value('PT1')`` or simple arithmetic on it.

    Examples:
        {"type": "label_expr", "expression": "item.get_label_value('PT1')"}
        {"type": "label_expr", "expression": "float(item.get_label_value('PT1')) * 60"}
    """
    type: Literal["label_expr"]
    expression: str = Field(
        min_length=1,
        description=(
            "Python expression evaluated per item. "
            "'item' is the Item instance currently being processed. "
            "Must return a non-negative number. "
            "Example: \"item.get_label_value('PT1')\""
        ),
    )


# ServiceTimeSpec accepts either a statistical distribution OR a label expression.
ServiceTimeSpec = Annotated[
    Union[ExponDist, UniformDist, NormDist, TriangDist, LabelExprSpec],
    Field(discriminator="type"),
]


